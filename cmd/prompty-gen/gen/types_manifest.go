const (
	composeConditionKindBool   = "bool"
	composeConditionKindString = jsonSchemaTypeString
	composeConditionKindInt    = "int"
	composeConditionKindFloat  = "float"
)

// toPascal converts manifest id (e.g. "support-agent") to PascalCase (e.g. SupportAgent).
func toPascal(s string) string {
	return pascal(strings.ReplaceAll(s, "-", "_"))
}

func schemaAsMap(doc prompty.JSONDocument) (map[string]any, error) {
	if len(doc) == 0 {
		return map[string]any{}, nil
	}
	return prompty.JSONDocumentAsMap(doc)
}

// isStructSchema returns true when ResponseFormat defines an object schema with non-empty properties.
func isStructSchema(rf *prompty.SchemaDefinition) bool {
	if rf == nil || len(rf.Schema) == 0 {
		return false
	}
	schema, err := schemaAsMap(rf.Schema)
	if err != nil {
		return false
	}
	typ, _ := schema["type"].(string)
	if typ != jsonSchemaTypeObject {
		return false
	}
	props, _ := schema["properties"].(map[string]any)
	return len(props) > 0
}

// GenerateManifestTypes produces a per-manifest _gen.go file.
// Contains: const PromptID, Input/Output types, <Name>Prompt with recipe/RequiredTools/ID methods.
//
//nolint:funlen // early/late split + recipe wrapper
func GenerateManifestTypes(spec *PromptSpec, pkgName string) (*jen.File, error) {
	f := jen.NewFile(pkgName)
	f.HeaderComment("Code generated by prompty-gen. DO NOT EDIT.")

	rootName := toPascal(spec.ID)
	promptType := rootName + "Prompt"
	recipeType := rootName + "Recipe"
	composeContextType := rootName + "ComposeContext"
	constName := idToConstName(spec.ID)
	inputType := rootName + "Input"

	f.ImportName("context", "context")
	f.ImportName("encoding/json", "json")
	f.ImportName("fmt", "fmt")
	f.ImportName("github.com/skosovsky/prompty", "prompty")

	f.Const().Id(constName).Id("PromptID").Op("=").Lit(spec.ID)
	f.Line()

	m := newSchemaMapper(rootName)
	lateInputType := rootName + "LateInput"
	var earlyInputSchema *prompty.SchemaDefinition
	hasLateInput := false
	hasInputSchema := spec.InputSchema != nil && len(spec.InputSchema.Schema) > 0
	if hasInputSchema {
		inputSchema, err := schemaAsMap(spec.InputSchema.Schema)
		if err != nil {
			return nil, fmt.Errorf("input schema: %w", err)
		}
		if validateErr := validateObjectSchemaForInput(inputSchema); validateErr != nil {
			return nil, fmt.Errorf("input schema: %w", validateErr)
		}
		earlySchema, lateSchema, hasLate := splitEarlyLateInputSchema(inputSchema)
		hasLateInput = hasLate
		earlyInputSchema, err = schemaDefinitionFromMap(earlySchema)
		if err != nil {
			return nil, fmt.Errorf("input schema: %w", err)
		}
		earlyProps, _ := earlySchema["properties"].(map[string]any)
		if len(earlyProps) > 0 {
			stmts, genErr := m.GenerateTypes(earlySchema, "Input")
			if genErr != nil {
				return nil, fmt.Errorf("input schema: %w", genErr)
			}
			for _, stmt := range stmts {
				f.Add(stmt)
				f.Line()
			}
		} else {
			f.Type().Id(inputType).Struct()
			f.Line()
		}
		if hasLateInput {
			lateMapper := newSchemaMapper(rootName)
			lateStmts, genErr := lateMapper.GenerateTypes(lateSchema, "LateInput")
			if genErr != nil {
				return nil, fmt.Errorf("late input schema: %w", genErr)
			}
			for _, stmt := range lateStmts {
				f.Add(stmt)
				f.Line()
			}
		}
	} else {
		f.Type().Id(inputType).Struct()
		f.Line()
	}

	hasOutputSchema := isStructSchema(spec.ResponseFormat)
	if hasOutputSchema {
		outputSchema, err := schemaAsMap(spec.ResponseFormat.Schema)
		if err != nil {
			return nil, fmt.Errorf("response format: %w", err)
		}
		stmts, err := m.GenerateTypes(outputSchema, "Output")
		if err != nil {
			return nil, fmt.Errorf("response format: %w", err)
		}
		for _, stmt := range stmts {
			f.Add(stmt)
			f.Line()
		}
	}

	composeConditions, err := normalizeComposeConditions(spec.ComposeConditions)
	if err != nil {
		return nil, err
	}
	requiresComposeContext := len(composeConditions) > 0
	if requiresComposeContext {
		addComposeContextType(
			f,
			rootName,
			inputType,
			composeContextType,
			constName,
			composeConditions,
		)
		f.Line()
	}

	f.Type().Id(promptType).Struct(
		jen.Id("registry").Qual("github.com/skosovsky/prompty", "PromptCatalogRegistry"),
	)
	f.Line()

	renderSchema := spec.InputSchema
	if earlyInputSchema != nil {
		renderSchema = earlyInputSchema
	}
	if recipeErr := addRecipeTypeAndMethods(
		f,
		recipeType,
		inputType,
		lateInputType,
		hasLateInput,
		composeContextType,
		constName,
		requiresComposeContext,
		renderSchema,
		composeConditions,
	); recipeErr != nil {
		return nil, recipeErr
	}
	f.Line()

	recipeBody, err := buildRecipeMethodBody(
		renderSchema,
		constName,
		recipeType,
		inputType,
		lateInputType,
		hasLateInput,
	)
	if err != nil {
		return nil, err
	}
	if !requiresComposeContext {
		f.Func().Params(jen.Id("p").Op("*").Id(promptType)).Id("NewRecipe").Params(
			jen.Id("ctx").Qual("context", "Context"),
			jen.Id("input").Id(inputType),
		).Parens(jen.List(jen.Id(recipeType), jen.Error())).Block(
			jen.Return(jen.Id("p").Dot("newRecipe").Call(jen.Id("ctx"), jen.Id("input"))),
		)
		f.Line()
	}

	f.Func().Params(jen.Id("p").Op("*").Id(promptType)).Id("newRecipe").Params(
		jen.Id("ctx").Qual("context", "Context"),
		jen.Id("input").Id(inputType),
		jen.Id("options").Op("...").Qual("github.com/skosovsky/prompty", "PromptRuntimeOptions"),
	).Parens(jen.List(jen.Id(recipeType), jen.Error())).Block(recipeBody...)
	f.Line()

	if requiresComposeContext {
		f.Func().
			Params(jen.Id("p").Op("*").Id(promptType)).
			Id("NewRecipeWithComposeContext").
			Params(
				jen.Id("ctx").Qual("context", "Context"),
				jen.Id("input").Id(inputType),
				jen.Id("compose").Id(composeContextType),
			).
			Parens(jen.List(jen.Id(recipeType), jen.Error())).
			Block(
				jen.List(jen.Id("options"), jen.Id("err")).Op(":=").Qual(
					"github.com/skosovsky/prompty",
					"PromptRuntimeOptionsFromComposeContext",
				).Call(jen.Id("compose")),
				jen.If(jen.Id("err").Op("!=").Nil()).Block(
					jen.Return(jen.Id(recipeType).Values(), jen.Id("err")),
				),
				jen.Return(jen.Id("p").Dot("newRecipe").Call(jen.Id("ctx"), jen.Id("input"), jen.Id("options"))),
			)
		f.Line()
	}

	f.Func().
		Params(jen.Id("p").Op("*").Id(promptType)).
		Id("RequiredTools").
		Params().
		Index().
		String().
		Block(
			requiredToolsReturn(spec.RequiredTools),
		)
	f.Line()

	f.Func().Params(jen.Id("p").Op("*").Id(promptType)).Id("ID").Params().Id("PromptID").Block(
		jen.Return(jen.Id(constName)),
	)

	return f, nil
}

func normalizeComposeConditions(in []ComposeConditionSpec) ([]ComposeConditionSpec, error) {
	out := make([]ComposeConditionSpec, 0, len(in))
	seen := make(map[string]struct{}, len(in))
	seenFields := make(map[string]string, len(in))
	for _, cond := range in {
		if cond.Key == "" {
			continue
		}
		if _, exists := seen[cond.Key]; exists {
			continue
		}
		seen[cond.Key] = struct{}{}
		if cond.FieldName == "" {
			cond.FieldName = pascal(strings.NewReplacer(".", "_", "-", "_").Replace(cond.Key))
		}
		if prevKey, exists := seenFields[cond.FieldName]; exists && prevKey != cond.Key {
			return nil, fmt.Errorf(
				"compose condition %q: field name %q collides with %q",
				cond.Key,
				cond.FieldName,
				prevKey,
			)
		}
		seenFields[cond.FieldName] = cond.Key
		if cond.Kind == "" {
			cond.Kind = composeConditionKindBool
		}
		switch cond.Kind {
		case composeConditionKindBool,
			composeConditionKindString,
			composeConditionKindInt,
			composeConditionKindFloat:
		default:
			return nil, fmt.Errorf("compose condition %q: unsupported kind %q", cond.Key, cond.Kind)
		}
		out = append(out, cond)
	}
	return out, nil
}

//nolint:funlen // emits a cohesive generated compose-context API surface.
func addComposeContextType(
	f *jen.File,
	rootName string,
	inputType string,
	typeName string,
	constName string,
	conditions []ComposeConditionSpec,
) {
	fields := make([]jen.Code, 0, len(conditions))
	for _, cond := range conditions {
		fields = append(fields, jen.Id(cond.FieldName).
			Op("*").Add(composeConditionType(cond.Kind)).
			Tag(map[string]string{"json": composeConditionJSONName(cond)}))
	}
	f.Type().Id(typeName).Struct(fields...)
	f.Line()

	constructorParams := make([]jen.Code, 0, len(conditions))
	constructorValues := make([]jen.Code, 0, len(conditions))
	for _, cond := range conditions {
		paramName := composeConditionParamName(cond)
		constructorParams = append(
			constructorParams,
			jen.Id(paramName).Add(composeConditionType(cond.Kind)),
		)
		constructorValues = append(
			constructorValues,
			jen.Id(cond.FieldName).Op(":").Op("&").Id(paramName),
		)
	}
	f.Func().Id("New" + typeName).Params(constructorParams...).Id(typeName).Block(
		jen.Return(jen.Id(typeName).Values(constructorValues...)),
	)
	f.Line()

	validateStmts := make([]jen.Code, 0, len(conditions)+1)
	for _, cond := range conditions {
		validateStmts = append(validateStmts,
			jen.If(jen.Id("c").Dot(cond.FieldName).Op("==").Nil()).Block(
				jen.Return(jen.Qual("fmt", "Errorf").Call(
					jen.Lit("%s compose context requires %q"),
					jen.Id("string").Call(jen.Id(constName)),
					jen.Lit(cond.Key),
				)),
			),
		)
	}
	validateStmts = append(validateStmts, jen.Return(jen.Nil()))
	f.Func().Params(jen.Id("c").Id(typeName)).Id("ValidateComposeContext").Params().Error().Block(
		validateStmts...,
	)
	f.Line()

	appendPairStmts := []jen.Code{
		jen.Id("pairs").Op(":=").Make(
			jen.Index().Qual("github.com/skosovsky/prompty", "ComposeValue"),
			jen.Lit(0),
			jen.Lit(len(conditions)),
		),
	}
	for _, cond := range conditions {
		appendPairStmts = append(appendPairStmts,
			jen.If(jen.Id("c").Dot(cond.FieldName).Op("!=").Nil()).Block(
				jen.Id("pairs").Op("=").Append(
					jen.Id("pairs"),
					jen.Qual("github.com/skosovsky/prompty", composeConditionCtor(cond.Kind)).Call(
						jen.Lit(cond.Key),
						jen.Op("*").Id("c").Dot(cond.FieldName),
					),
				),
			),
		)
	}
	appendPairStmts = append(
		appendPairStmts,
		jen.Return(
			jen.Qual("github.com/skosovsky/prompty", "NewComposeValuesFromPairs").
				Call(jen.Id("pairs").Op("...")),
		),
	)
	f.Func().Params(jen.Id("c").Id(typeName)).Id("ComposeValues").Params().
		Qual("github.com/skosovsky/prompty", "ComposeValues").Block(appendPairStmts...)
	f.Line()

	f.Func().Id(composeLookupFuncName(rootName+"Recipe")).Params(
		jen.Id("values").Map(jen.String()).Interface(),
		jen.Id("path").String(),
	).Parens(jen.List(jen.Interface(), jen.Bool())).Block(
		jen.If(jen.Id("path").Op("==").Lit("")).Block(
			jen.Return(jen.Nil(), jen.False()),
		),
		jen.Var().Id("cur").Interface().Op("=").Id("values"),
		jen.For(jen.List(jen.Id("_"), jen.Id("part")).Op(":=").Range().Qual("strings", "Split").Call(
			jen.Id("path"),
			jen.Lit("."),
		)).
			Block(
				jen.List(jen.Id("m"), jen.Id("ok")).
					Op(":=").
					Id("cur").
					Assert(jen.Map(jen.String()).Interface()),
				jen.If(jen.Op("!").Id("ok")).Block(
					jen.Return(jen.Nil(), jen.False()),
				),
				jen.List(jen.Id("next"), jen.Id("ok")).Op(":=").Id("m").Index(jen.Id("part")),
				jen.If(jen.Op("!").Id("ok")).Block(
					jen.Return(jen.Nil(), jen.False()),
				),
				jen.Id("cur").Op("=").Id("next"),
			),
		jen.Return(jen.Id("cur"), jen.True()),
	)
	f.Line()

	f.Type().Id(rootName+"RecipePayload").Struct(
		jen.Id("Input").Id(inputType).Tag(map[string]string{"json": "input"}),
		jen.Id("Compose").Op("*").Id(typeName).Tag(map[string]string{"json": "compose"}),
	)
}

func composeConditionParamName(cond ComposeConditionSpec) string {
	if cond.FieldName == "" {
		return "value"
	}
	return lowerFirstASCII(cond.FieldName)
}

func lowerFirstASCII(s string) string {
	if s == "" {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

func composeConditionType(kind string) jen.Code {
	switch kind {
	case composeConditionKindBool:
		return jen.Bool()
	case composeConditionKindString:
		return jen.String()
	case composeConditionKindInt:
		return jen.Int64()
	case composeConditionKindFloat:
		return jen.Float64()
	default:
		return jen.Bool()
	}
}

func composeConditionCtor(kind string) string {
	switch kind {
	case composeConditionKindBool:
		return "ComposeBool"
	case composeConditionKindString:
		return "ComposeString"
	case composeConditionKindInt:
		return "ComposeInt"
	case composeConditionKindFloat:
		return "ComposeFloat"
	default:
		return "ComposeBool"
	}
}

func composeConditionJSONName(cond ComposeConditionSpec) string {
	return strings.NewReplacer(".", "_", "-", "_").Replace(cond.Key)
}

//nolint:funlen // emits a cohesive generated recipe API surface.
func addRecipeTypeAndMethods(
	f *jen.File,
	recipeType string,
	inputType string,
	lateInputType string,
	hasLateInput bool,
	composeContextType string,
	constName string,
	requiresComposeContext bool,
	inputSchema *prompty.SchemaDefinition,
	composeConditions []ComposeConditionSpec,
) error {
	innerType := jen.Qual("github.com/skosovsky/prompty", "PromptRecipeNoLate").
		Types(jen.Id(inputType))
	checkpointType := jen.Qual("github.com/skosovsky/prompty", "PromptRecipeNoLateCheckpoint").
		Types(jen.Id(inputType))
	if hasLateInput {
		innerType = jen.Qual("github.com/skosovsky/prompty", "PromptRecipe").
			Types(jen.Id(inputType), jen.Id(lateInputType))
		checkpointType = jen.Qual("github.com/skosovsky/prompty", "PromptRecipeCheckpoint").
			Types(jen.Id(inputType), jen.Id(lateInputType))
	}
	f.Type().Id(recipeType).Struct(jen.Id("inner").Add(innerType))
	f.Line()

	restoreCall := jen.Qual("github.com/skosovsky/prompty", "PromptRecipeNoLateFromCheckpoint").
		Types(jen.Id(inputType)).
		Call(jen.Id("checkpoint"))
	if hasLateInput {
		restoreCall = jen.Qual("github.com/skosovsky/prompty", "PromptRecipeFromCheckpoint").Types(
			jen.Id(inputType),
			jen.Id(lateInputType),
		).Call(jen.Id("checkpoint"))
	}
	restoreBody := []jen.Code{
		jen.If(jen.Id("checkpoint").Dot("Descriptor").Dot("ID").Op("!=").Id("string").Call(jen.Id(constName))).
			Block(
				jen.Return(
					jen.Id(recipeType).Values(),
					jen.Qual("fmt", "Errorf").Call(
						jen.Lit("%s checkpoint descriptor id mismatch: %q"),
						jen.Id("string").Call(jen.Id(constName)),
						jen.Id("checkpoint").Dot("Descriptor").Dot("ID"),
					),
				),
			),
	}
	inputValidationBlock, err := buildRecipeInputValidationBlock(inputSchema, recipeType)
	if err != nil {
		return err
	}
	restoreBody = append(restoreBody,
		jen.Id("input").Op(":=").Id("checkpoint").Dot("Input"),
	)
	restoreBody = append(restoreBody, inputValidationBlock...)
	restoreBody = append(restoreBody,
		jen.Id("checkpoint").Dot("Input").Op("=").Id("input"),
	)
	if requiresComposeContext {
		restoreBody = append(
			restoreBody,
			composeContextCheckpointGuard(recipeType, constName, composeConditions),
		)
	}
	restoreBody = append(restoreBody,
		jen.List(jen.Id("inner"), jen.Id("err")).Op(":=").Add(restoreCall),
		jen.If(jen.Id("err").Op("!=").Nil()).Block(
			jen.Return(jen.Id(recipeType).Values(), jen.Id("err")),
		),
		jen.Return(jen.Id(recipeType).Values(jen.Id("inner").Op(":").Id("inner")), jen.Nil()),
	)
	f.Func().Id("New" + recipeType + "FromCheckpoint").Params(
		jen.Id("checkpoint").Add(checkpointType),
	).Parens(jen.List(jen.Id(recipeType), jen.Error())).Block(restoreBody...)
	f.Line()

	f.Func().Params(jen.Id("r").Id(recipeType)).Id("PromptID").Params().Id("PromptID").Block(
		jen.Return(jen.Id(constName)),
	)
	f.Line()

	f.Func().Params(jen.Id("r").Id(recipeType)).Id("Checkpoint").Params().Parens(
		jen.List(checkpointType, jen.Error()),
	).Block(
		jen.Return(jen.Id("r").Dot("inner").Dot("Checkpoint").Call()),
	)
	f.Line()

	f.Func().Params(jen.Id("r").Id(recipeType)).Id("CheckpointJSON").Params().Parens(
		jen.List(jen.Index().Byte(), jen.Error()),
	).Block(
		jen.List(jen.Id("checkpoint"), jen.Id("err")).Op(":=").Id("r").Dot("Checkpoint").Call(),
		jen.If(jen.Id("err").Op("!=").Nil()).Block(
			jen.Return(jen.Nil(), jen.Id("err")),
		),
		jen.Return(jen.Qual("encoding/json", "Marshal").Call(jen.Id("checkpoint"))),
	)
	f.Line()

	f.Func().Params(jen.Id("r").Id(recipeType)).Id("Descriptor").Params().
		Qual("github.com/skosovsky/prompty", "ManifestDescriptor").Block(
		jen.Return(jen.Id("r").Dot("inner").Dot("Descriptor")),
	)
	f.Line()

	if requiresComposeContext {
		addRecipeTransformMethod(f, recipeType, "WithComposeContext", "ctx", composeContextType)
	}

	if hasLateInput {
		addRecipeTransformMethod(f, recipeType, "BindLate", "input", lateInputType)
	}

	f.Func().Params(jen.Id("r").Id(recipeType)).Id("Execute").Params(
		jen.Id("ctx").Qual("context", "Context"),
		jen.Id("registry").Qual("github.com/skosovsky/prompty", "ManifestCheckpointRegistry"),
	).Parens(jen.List(jen.Op("*").Qual("github.com/skosovsky/prompty", "PromptExecution"), jen.Error())).Block(
		jen.Return(jen.Id("r").Dot("inner").Dot("Execute").Call(jen.Id("ctx"), jen.Id("registry"))),
	)
	f.Line()

	f.Func().Params(jen.Id("r").Id(recipeType)).Id("ExecuteWithContract").Params(
		jen.Id("ctx").Qual("context", "Context"),
		jen.Id("registry").Qual("github.com/skosovsky/prompty", "ManifestCheckpointRegistry"),
		jen.Id("contract").Qual("github.com/skosovsky/prompty", "ToolContract"),
	).Parens(jen.List(jen.Op("*").Qual("github.com/skosovsky/prompty", "PromptExecution"), jen.Error())).Block(
		jen.Return(jen.Id("r").Dot("inner").Dot("ExecuteWithContract").Call(
			jen.Id("ctx"),
			jen.Id("registry"),
			jen.Id("contract"),
		)),
	)
	return nil
}

func addRecipeTransformMethod(
	f *jen.File,
	recipeType string,
	methodName string,
	paramName string,
	paramType string,
) {
	f.Func().Params(jen.Id("r").Id(recipeType)).Id(methodName).Params(
		jen.Id(paramName).Id(paramType),
	).Parens(jen.List(jen.Id(recipeType), jen.Error())).Block(
		jen.List(jen.Id("inner"), jen.Id("err")).
			Op(":=").
			Id("r").
			Dot("inner").
			Dot(methodName).
			Call(jen.Id(paramName)),
		jen.If(jen.Id("err").Op("!=").Nil()).Block(
			jen.Return(jen.Id(recipeType).Values(), jen.Id("err")),
		),
		jen.Return(jen.Id(recipeType).Values(jen.Id("inner").Op(":").Id("inner")), jen.Nil()),
	)
	f.Line()
}

func composeContextCheckpointGuard(
	recipeType string,
	constName string,
	conditions []ComposeConditionSpec,
) jen.Code {
	body := []jen.Code{
		jen.If(jen.Len(jen.Id("checkpoint").Dot("RuntimeOptions").Dot("ComposeValues")).Op("==").Lit(0)).
			Block(
				jen.Return(
					jen.Id(recipeType).Values(),
					jen.Qual("fmt", "Errorf").Call(
						jen.Lit("%s checkpoint requires compose context"),
						jen.Id("string").Call(jen.Id(constName)),
					),
				),
			),
		jen.List(jen.Id("composeValues"), jen.Id("err")).Op(":=").Qual(
			"github.com/skosovsky/prompty",
			"JSONDocumentAsMap",
		).Call(jen.Id("checkpoint").Dot("RuntimeOptions").Dot("ComposeValues")),
		jen.If(jen.Id("err").Op("!=").Nil()).Block(
			jen.Return(
				jen.Id(recipeType).Values(),
				jen.Qual("fmt", "Errorf").Call(
					jen.Lit("%s checkpoint compose context: %w"),
					jen.Id("string").Call(jen.Id(constName)),
					jen.Id("err"),
				),
			),
		),
	}
	for _, cond := range conditions {
		valueName := "value" + cond.FieldName
		okName := "ok" + cond.FieldName
		body = append(
			body,
			jen.List(jen.Id(valueName), jen.Id(okName)).
				Op(":=").
				Id(composeLookupFuncName(recipeType)).
				Call(
					jen.Id("composeValues"),
					jen.Lit(cond.Key),
				),
			jen.If(jen.Op("!").Id(okName)).Block(
				jen.Return(
					jen.Id(recipeType).Values(),
					jen.Qual("fmt", "Errorf").Call(
						jen.Lit("%s checkpoint compose context requires %q"),
						jen.Id("string").Call(jen.Id(constName)),
						jen.Lit(cond.Key),
					),
				),
			),
			composeConditionRuntimeTypeGuard(recipeType, constName, cond, valueName),
		)
	}
	return jen.Block(body...)
}

func composeLookupFuncName(recipeType string) string {
	return lowerFirstASCII(strings.TrimSuffix(recipeType, "Recipe")) + "ComposeValue"
}

func composeConditionRuntimeTypeGuard(
	recipeType string,
	constName string,
	cond ComposeConditionSpec,
	valueName string,
) jen.Code {
	okName := "typeOK" + cond.FieldName
	switch cond.Kind {
	case composeConditionKindBool:
		return jen.If(
			jen.List(jen.Id("_"), jen.Id(okName)).Op(":=").Id(valueName).Assert(jen.Bool()),
			jen.Op("!").Id(okName),
		).Block(composeConditionTypeErrorReturn(recipeType, constName, cond, "bool"))
	case composeConditionKindString:
		return jen.If(
			jen.List(jen.Id("_"), jen.Id(okName)).Op(":=").Id(valueName).Assert(jen.String()),
			jen.Op("!").Id(okName),
		).Block(composeConditionTypeErrorReturn(recipeType, constName, cond, "string"))
	case composeConditionKindInt:
		numberName := "number" + cond.FieldName
		return jen.If(
			jen.List(jen.Id(numberName), jen.Id(okName)).
				Op(":=").
				Id(valueName).
				Assert(jen.Float64()),
			jen.Op("!").
				Id(okName).
				Op("||").
				Qual("math", "Trunc").
				Call(jen.Id(numberName)).
				Op("!=").
				Id(numberName),
		).Block(composeConditionTypeErrorReturn(recipeType, constName, cond, "integer"))
	case composeConditionKindFloat:
		return jen.If(
			jen.List(jen.Id("_"), jen.Id(okName)).Op(":=").Id(valueName).Assert(jen.Float64()),
			jen.Op("!").Id(okName),
		).Block(composeConditionTypeErrorReturn(recipeType, constName, cond, "number"))
	default:
		return jen.Empty()
	}
}

func composeConditionTypeErrorReturn(
	recipeType string,
	constName string,
	cond ComposeConditionSpec,
	want string,
) jen.Code {
	return jen.Return(
		jen.Id(recipeType).Values(),
		jen.Qual("fmt", "Errorf").Call(
			jen.Lit("%s checkpoint compose context %q must be "+want),
			jen.Id("string").Call(jen.Id(constName)),
			jen.Lit(cond.Key),
		),
	)
}

func buildRecipeMethodBody(
	inputSchema *prompty.SchemaDefinition,
	constName string,
	recipeType string,
	inputType string,
	lateInputType string,
	hasLateInput bool,
) ([]jen.Code, error) {
	body := []jen.Code{
		jen.If(jen.Id("p").Dot("registry").Op("==").Nil()).Block(
			jen.Return(jen.List(
				jen.Id(recipeType).Values(),
				jen.Qual("fmt", "Errorf").Call(
					jen.Lit("%s recipe requires registry"),
					jen.Id("string").Call(jen.Id(constName)),
				),
			)),
		),
	}
	inputValidationBlock, err := buildRecipeInputValidationBlock(inputSchema, recipeType)
	if err != nil {
		return nil, err
	}
	body = append(body, inputValidationBlock...)
	body = append(
		body,
		jen.List(jen.Id("desc"), jen.Id("err")).
			Op(":=").
			Id("p").
			Dot("registry").
			Dot("RecommendManifestDescriptor").
			Call(
				jen.Id("ctx"),
				jen.Id("string").Call(jen.Id(constName)),
			),
		jen.If(jen.Id("err").Op("!=").Nil()).Block(
			jen.Return(jen.List(jen.Id(recipeType).Values(), jen.Qual("fmt", "Errorf").Call(jen.Lit("recommend manifest descriptor: %w"), jen.Id("err")))),
		),
	)
	newRecipe := jen.Qual("github.com/skosovsky/prompty", "NewPromptRecipeNoLate").
		Types(jen.Id(inputType)).
		Call(jen.Id("desc"), jen.Id("input"), jen.Id("options").Op("..."))
	if hasLateInput {
		newRecipe = jen.Qual("github.com/skosovsky/prompty", "NewPromptRecipe").
			Types(jen.Id(inputType), jen.Id(lateInputType)).
			Call(jen.Id("desc"), jen.Id("input"), jen.Id("options").Op("..."))
	}
	body = append(body,
		jen.List(jen.Id("inner"), jen.Id("err")).Op(":=").Add(newRecipe),
		jen.If(jen.Id("err").Op("!=").Nil()).Block(
			jen.Return(jen.List(jen.Id(recipeType).Values(), jen.Id("err"))),
		),
		jen.Return(jen.Id(recipeType).Values(jen.Id("inner").Op(":").Id("inner")), jen.Nil()),
	)
	return body, nil
}

func buildRecipeInputValidationBlock(
	inputSchema *prompty.SchemaDefinition,
	recipeType string,
) ([]jen.Code, error) {
	defaultStmts, err := buildInputDefaultsBlock(inputSchema)
	if err != nil {
		return nil, err
	}
	body := append([]jen.Code{}, defaultStmts...)
	body = append(
		body,
		jen.If(jen.Id("err").Op(":=").Id("validate").Dot("Struct").Call(jen.Op("&").Id("input")).Op(";").Id("err").Op("!=").Nil()).
			Block(
				jen.Return(jen.List(jen.Id(recipeType).Values(), jen.Qual("fmt", "Errorf").Call(jen.Lit("validate input: %w"), jen.Id("err")))),
			),
	)
	if inputSchemaHasBindableProperties(inputSchema) {
		body = append(body,
			jen.If(
				jen.List(jen.Id("_"), jen.Id("err")).
					Op(":=").
					Qual("github.com/skosovsky/prompty", "PlanInputFrom").
					Call(jen.Id("input")),
				jen.Id("err").Op("!=").Nil(),
			).
				Block(
					jen.Return(jen.List(jen.Id(recipeType).Values(), jen.Qual("fmt", "Errorf").Call(jen.Lit("bind recipe input: %w"), jen.Id("err")))),
				),
		)
	}
	return body, nil
}

func requiredToolsReturn(tools []string) jen.Code {
	if len(tools) == 0 {
		return jen.Return(jen.Index().String().Values())
	}
	lits := make([]jen.Code, len(tools))
	for i, t := range tools {
		lits[i] = jen.Lit(t)
	}
	return jen.Return(jen.Index().String().Values(lits...))
}

func inputSchemaHasBindableProperties(schemaDef *prompty.SchemaDefinition) bool {
	if schemaDef == nil || len(schemaDef.Schema) == 0 {
		return false
	}
	schema, err := schemaAsMap(schemaDef.Schema)
	if err != nil {
		return false
	}
	props, _ := schema["properties"].(map[string]any)
	return len(props) > 0
}

func buildInputDefaultsBlock(schemaDef *prompty.SchemaDefinition) ([]jen.Code, error) {
	if !inputSchemaHasBindableProperties(schemaDef) {
		return nil, nil
	}
	schema, err := schemaAsMap(schemaDef.Schema)
	if err != nil {
		return nil, err
	}
	props, _ := schema["properties"].(map[string]any)
	required := getRequired(schema)
	stmts := make([]jen.Code, 0, len(props))
	for _, propName := range sortedKeys(props) {
		propSchema, _ := props[propName].(map[string]any)
		if propSchema == nil || required[propName] {
			continue
		}
		defVal, hasDefault := propSchema["default"]
		if !hasDefault {
			continue
		}
		fieldName := pascal(propName)
		propType, _ := propSchema["type"].(string)
		switch propType {
		case jsonSchemaTypeString:
			defStr, ok := defVal.(string)
			if !ok {
				return nil, fmt.Errorf(
					"input schema default for %q: expected string default value",
					propName,
				)
			}
			stmts = append(stmts,
				jen.If(jen.Id("input").Dot(fieldName).Op("==").Nil()).Block(
					jen.Id("v").Op(":=").Lit(defStr),
					jen.Id("input").Dot(fieldName).Op("=").Op("&").Id("v"),
				),
			)
		case jsonSchemaTypeInteger:
			defNum, ok := toFloat(defVal)
			if !ok {
				return nil, fmt.Errorf(
					"input schema default for %q: expected numeric default value",
					propName,
				)
			}
			stmts = append(stmts,
				jen.If(jen.Id("input").Dot(fieldName).Op("==").Nil()).Block(
					jen.Id("v").Op(":=").Lit(int64(defNum)),
					jen.Id("input").Dot(fieldName).Op("=").Op("&").Id("v"),
				),
			)
		case jsonSchemaTypeNumber:
			defNum, ok := toFloat(defVal)
			if !ok {
				return nil, fmt.Errorf(
					"input schema default for %q: expected numeric default value",
					propName,
				)
			}
			stmts = append(stmts,
				jen.If(jen.Id("input").Dot(fieldName).Op("==").Nil()).Block(
					jen.Id("v").Op(":=").Lit(defNum),
					jen.Id("input").Dot(fieldName).Op("=").Op("&").Id("v"),
				),
			)
		case jsonSchemaTypeBoolean:
			defBool, ok := defVal.(bool)
			if !ok {
				return nil, fmt.Errorf(
					"input schema default for %q: expected boolean default value",
					propName,
				)
			}
			stmts = append(stmts,
				jen.If(jen.Id("input").Dot(fieldName).Op("==").Nil()).Block(
					jen.Id("v").Op(":=").Lit(defBool),
					jen.Id("input").Dot(fieldName).Op("=").Op("&").Id("v"),
				),
			)
		default:
			return nil, fmt.Errorf(
				"input schema default for %q: unsupported type %q (supported: string, integer, number, boolean)",
				propName,
				propType,
			)
		}
	}
	return stmts, nil
}
