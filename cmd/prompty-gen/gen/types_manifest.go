// toPascal converts manifest id (e.g. "support-agent") to PascalCase (e.g. SupportAgent).
func toPascal(s string) string {
	return pascal(strings.ReplaceAll(s, "-", "_"))
}

// isStructSchema returns true when ResponseFormat defines an object schema with non-empty properties.
func isStructSchema(rf *prompty.SchemaDefinition) bool {
	if rf == nil || rf.Schema == nil {
		return false
	}
	typ, _ := rf.Schema["type"].(string)
	if typ != jsonSchemaTypeObject {
		return false
	}
	props, _ := rf.Schema["properties"].(map[string]any)
	return len(props) > 0
}

// GenerateManifestTypes produces a per-manifest _gen.go file.
// Contains: const PromptID, Input/Output types, <Name>Prompt with Render/renderFromAny/RequiredTools/ID methods.
func GenerateManifestTypes(spec *PromptSpec, pkgName string) (*jen.File, error) {
	f := jen.NewFile(pkgName)
	f.HeaderComment("Code generated by prompty-gen. DO NOT EDIT.")

	rootName := toPascal(spec.ID)
	promptType := rootName + "Prompt"
	constName := idToConstName(spec.ID)
	inputType := rootName + "Input"

	f.ImportName("context", "context")
	f.ImportName("fmt", "fmt")
	f.ImportName("github.com/skosovsky/prompty", "prompty")

	f.Const().Id(constName).Id("PromptID").Op("=").Lit(spec.ID)
	f.Line()

	m := newSchemaMapper(rootName)
	hasInputSchema := spec.InputSchema != nil && spec.InputSchema.Schema != nil
	if hasInputSchema {
		if err := validateObjectSchemaForInput(spec.InputSchema.Schema); err != nil {
			return nil, fmt.Errorf("input schema: %w", err)
		}
		stmts, err := m.GenerateTypes(spec.InputSchema.Schema, "Input")
		if err != nil {
			return nil, fmt.Errorf("input schema: %w", err)
		}
		for _, stmt := range stmts {
			f.Add(stmt)
			f.Line()
		}
	} else {
		f.Type().Id(inputType).Struct()
		f.Line()
	}

	hasOutputSchema := isStructSchema(spec.ResponseFormat)
	if hasOutputSchema {
		stmts, err := m.GenerateTypes(spec.ResponseFormat.Schema, "Output")
		if err != nil {
			return nil, fmt.Errorf("response format: %w", err)
		}
		for _, stmt := range stmts {
			f.Add(stmt)
			f.Line()
		}
	}

	f.Type().Id(promptType).Struct(
		jen.Id("registry").Qual("github.com/skosovsky/prompty", "Registry"),
	)
	f.Line()

	renderBody := []jen.Code{}
	defaultStmts, err := buildInputDefaultsBlock(spec.InputSchema)
	if err != nil {
		return nil, err
	}
	renderBody = append(renderBody, defaultStmts...)
	renderBody = append(
		renderBody,
		jen.If(jen.Id("err").Op(":=").Id("validate").Dot("Struct").Call(jen.Op("&").Id("input")).Op(";").Id("err").Op("!=").Nil()).
			Block(
				jen.Return(jen.List(jen.Nil(), jen.Qual("fmt", "Errorf").Call(jen.Lit("validate input: %w"), jen.Id("err")))),
			),
		jen.List(jen.Id("plan"), jen.Id("err")).
			Op(":=").
			Id("p").
			Dot("registry").
			Dot("Plan").
			Call(jen.Id("ctx"), jen.Id("string").Call(jen.Id(constName)), jen.Id("input")),
		jen.If(jen.Id("err").Op("!=").Nil()).Block(
			jen.Return(jen.List(jen.Nil(), jen.Qual("fmt", "Errorf").Call(jen.Lit("build render plan: %w"), jen.Id("err")))),
		),
		jen.Return(jen.List(jen.Id("plan"), jen.Nil())),
	)

	f.Func().Params(jen.Id("p").Op("*").Id(promptType)).Id("Render").Params(
		jen.Id("ctx").Qual("context", "Context"),
		jen.Id("input").Id(inputType),
	).Parens(jen.List(jen.Op("*").Qual("github.com/skosovsky/prompty", "RenderPlan"), jen.Error())).Block(renderBody...)
	f.Line()

	f.Add(renderFromAnyMethod(promptType, inputType, constName))
	f.Line()

	f.Func().
		Params(jen.Id("p").Op("*").Id(promptType)).
		Id("RequiredTools").
		Params().
		Index().
		String().
		Block(
			requiredToolsReturn(spec.RequiredTools),
		)
	f.Line()

	f.Func().Params(jen.Id("p").Op("*").Id(promptType)).Id("ID").Params().Id("PromptID").Block(
		jen.Return(jen.Id(constName)),
	)

	return f, nil
}

func requiredToolsReturn(tools []string) jen.Code {
	if len(tools) == 0 {
		return jen.Return(jen.Index().String().Values())
	}
	lits := make([]jen.Code, len(tools))
	for i, t := range tools {
		lits[i] = jen.Lit(t)
	}
	return jen.Return(jen.Index().String().Values(lits...))
}

func renderFromAnyMethod(promptType, inputType, constName string) jen.Code {
	return jen.Func().Params(jen.Id("p").Op("*").Id(promptType)).Id("renderFromAny").Params(
		jen.Id("ctx").Qual("context", "Context"),
		jen.Id("input").Any(),
	).Parens(jen.List(jen.Op("*").Qual("github.com/skosovsky/prompty", "RenderPlan"), jen.Error())).Block(
		jen.Switch(jen.Id("typed").Op(":=").Id("input").Assert(jen.Type())).Block(
			jen.Case(jen.Id(inputType)).Block(
				jen.Return(jen.Id("p").Dot("Render").Call(jen.Id("ctx"), jen.Id("typed"))),
			),
			jen.Case(jen.Op("*").Id(inputType)).Block(
				jen.If(jen.Id("typed").Op("==").Nil()).Block(
					jen.Return(
						jen.List(
							jen.Nil(),
							jen.Qual("fmt", "Errorf").
								Call(jen.Lit("invalid input type for %s: got nil pointer"), jen.Id(constName)),
						),
					),
				),
				jen.Return(jen.Id("p").Dot("Render").Call(jen.Id("ctx"), jen.Op("*").Id("typed"))),
			),
			jen.Default().Block(
				jen.Var().Id("expected").Id(inputType),
				jen.Return(
					jen.List(
						jen.Nil(),
						jen.Qual("fmt", "Errorf").Call(
							jen.Lit("invalid input type for %s: expected %T, got %T"),
							jen.Id(constName),
							jen.Id("expected"),
							jen.Id("input"),
						),
					),
				),
			),
		),
	)
}

func buildInputDefaultsBlock(schemaDef *prompty.SchemaDefinition) ([]jen.Code, error) {
	if schemaDef == nil || schemaDef.Schema == nil {
		return nil, nil
	}
	schema := schemaDef.Schema
	props, _ := schema["properties"].(map[string]any)
	if len(props) == 0 {
		return nil, nil
	}
	required := getRequired(schema)
	stmts := make([]jen.Code, 0, len(props))
	for _, propName := range sortedKeys(props) {
		propSchema, _ := props[propName].(map[string]any)
		if propSchema == nil || required[propName] {
			continue
		}
		defVal, hasDefault := propSchema["default"]
		if !hasDefault {
			continue
		}
		fieldName := pascal(propName)
		propType, _ := propSchema["type"].(string)
		switch propType {
		case jsonSchemaTypeString:
			defStr, ok := defVal.(string)
			if !ok {
				return nil, fmt.Errorf(
					"input schema default for %q: expected string default value",
					propName,
				)
			}
			stmts = append(stmts,
				jen.If(jen.Id("input").Dot(fieldName).Op("==").Nil()).Block(
					jen.Id("v").Op(":=").Lit(defStr),
					jen.Id("input").Dot(fieldName).Op("=").Op("&").Id("v"),
				),
			)
		case jsonSchemaTypeInteger:
			defNum, ok := toFloat(defVal)
			if !ok {
				return nil, fmt.Errorf(
					"input schema default for %q: expected numeric default value",
					propName,
				)
			}
			stmts = append(stmts,
				jen.If(jen.Id("input").Dot(fieldName).Op("==").Nil()).Block(
					jen.Id("v").Op(":=").Lit(int64(defNum)),
					jen.Id("input").Dot(fieldName).Op("=").Op("&").Id("v"),
				),
			)
		case jsonSchemaTypeNumber:
			defNum, ok := toFloat(defVal)
			if !ok {
				return nil, fmt.Errorf(
					"input schema default for %q: expected numeric default value",
					propName,
				)
			}
			stmts = append(stmts,
				jen.If(jen.Id("input").Dot(fieldName).Op("==").Nil()).Block(
					jen.Id("v").Op(":=").Lit(defNum),
					jen.Id("input").Dot(fieldName).Op("=").Op("&").Id("v"),
				),
			)
		case jsonSchemaTypeBoolean:
			defBool, ok := defVal.(bool)
			if !ok {
				return nil, fmt.Errorf(
					"input schema default for %q: expected boolean default value",
					propName,
				)
			}
			stmts = append(stmts,
				jen.If(jen.Id("input").Dot(fieldName).Op("==").Nil()).Block(
					jen.Id("v").Op(":=").Lit(defBool),
					jen.Id("input").Dot(fieldName).Op("=").Op("&").Id("v"),
				),
			)
		default:
			return nil, fmt.Errorf(
				"input schema default for %q: unsupported type %q (supported: string, integer, number, boolean)",
				propName,
				propType,
			)
		}
	}
	return stmts, nil
}
