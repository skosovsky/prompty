package gen

import (
	"slices"

	"github.com/dave/jennifer/jen"
)

// GenerateSharedTypes produces the shared _shared_gen.go file for a package.
// Contains: type PromptID, PromptCatalog interface, constructor, RenderByID, typed render methods, validate, AllPromptIDs.
func GenerateSharedTypes(pkgName string, specs []*PromptSpec) (*jen.File, error) {
	f := jen.NewFile(pkgName)
	f.HeaderComment("Code generated by prompty-gen. DO NOT EDIT.")

	sorted := slices.Clone(specs)
	slices.SortFunc(sorted, func(a, b *PromptSpec) int {
		if a.ID < b.ID {
			return -1
		}
		if a.ID > b.ID {
			return 1
		}
		return 0
	})

	f.ImportName("github.com/skosovsky/prompty", "prompty")
	f.ImportName("github.com/go-playground/validator/v10", "validator")
	f.ImportName("context", "context")
	f.ImportName("fmt", "fmt")

	f.Type().Id("PromptID").String()
	f.Line()

	f.Var().Id("validate").Op("=").Qual("github.com/go-playground/validator/v10", "New").Call()
	f.Line()

	interfaceMethods := []jen.Code{
		jen.Id("RenderByID").Params(
			jen.Id("ctx").Qual("context", "Context"),
			jen.Id("id").Id("PromptID"),
			jen.Id("input").Any(),
		).Parens(jen.List(jen.Op("*").Qual("github.com/skosovsky/prompty", "RenderPlan"), jen.Error())),
	}

	var structFields []jen.Code
	switchCases := make([]jen.Code, 0, len(sorted)+1)
	for _, spec := range sorted {
		rootName := toPascal(spec.ID)
		interfaceMethods = append(interfaceMethods, jen.Id("Render"+rootName).Params(
			jen.Id("ctx").Qual("context", "Context"),
			jen.Id("input").Id(rootName+"Input"),
		).Parens(jen.List(jen.Op("*").Qual("github.com/skosovsky/prompty", "RenderPlan"), jen.Error())))
		structFields = append(structFields, jen.Id(rootName).Op("*").Id(rootName+"Prompt"))
		switchCases = append(switchCases, jen.Case(jen.Id(idToConstName(spec.ID))).Block(
			jen.Return(jen.Id("c").Dot(rootName).Dot("renderFromAny").Call(jen.Id("ctx"), jen.Id("input"))),
		))
	}
	switchCases = append(switchCases, jen.Default().Block(
		jen.Return(jen.List(jen.Nil(), jen.Qual("fmt", "Errorf").Call(jen.Lit("unknown prompt id: %q"), jen.Id("id")))),
	))

	f.Type().Id("PromptCatalog").Interface(interfaceMethods...)
	f.Line()

	f.Type().Id("promptCatalog").Struct(structFields...)
	f.Line()

	initDict := jen.Dict{}
	for _, spec := range sorted {
		rootName := toPascal(spec.ID)
		initDict[jen.Id(rootName)] = jen.Op("&").Id(rootName + "Prompt").Values(jen.Dict{
			jen.Id("registry"): jen.Id("r"),
		})
	}
	f.Func().Id("NewPromptCatalog").Params(
		jen.Id("r").Qual("github.com/skosovsky/prompty", "Registry"),
	).Id("PromptCatalog").Block(
		jen.Return(jen.Op("&").Id("promptCatalog").Values(initDict)),
	)
	f.Line()

	f.Func().Params(jen.Id("c").Op("*").Id("promptCatalog")).Id("RenderByID").Params(
		jen.Id("ctx").Qual("context", "Context"),
		jen.Id("id").Id("PromptID"),
		jen.Id("input").Any(),
	).Parens(jen.List(jen.Op("*").Qual("github.com/skosovsky/prompty", "RenderPlan"), jen.Error())).Block(
		jen.Switch(jen.Id("id")).Block(switchCases...),
	)
	f.Line()

	for _, spec := range sorted {
		rootName := toPascal(spec.ID)
		f.Func().Params(jen.Id("c").Op("*").Id("promptCatalog")).Id("Render"+rootName).Params(
			jen.Id("ctx").Qual("context", "Context"),
			jen.Id("input").Id(rootName+"Input"),
		).Parens(jen.List(jen.Op("*").Qual("github.com/skosovsky/prompty", "RenderPlan"), jen.Error())).Block(
			jen.Return(jen.Id("c").Dot(rootName).Dot("Render").Call(jen.Id("ctx"), jen.Id("input"))),
		)
		f.Line()
	}

	litVals := make([]jen.Code, len(sorted))
	for i, spec := range sorted {
		litVals[i] = jen.Id(idToConstName(spec.ID))
	}
	f.Func().Id("AllPromptIDs").Params().Index().Id("PromptID").Block(
		jen.Return(jen.Index().Id("PromptID").Values(litVals...)),
	)

	return f, nil
}
