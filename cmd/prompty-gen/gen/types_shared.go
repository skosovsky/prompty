// GenerateSharedTypes produces the shared _shared_gen.go file for a package.
// Contains: type PromptID, PromptCatalog interface, constructor, typed recipe methods, index, Descriptor, AllPromptIDs.
//
//nolint:funlen // emits the shared generated package API in declaration order.
func GenerateSharedTypes(pkgName string, specs []*PromptSpec) (*jen.File, error) {
	if err := validateSharedPromptSpecs(specs); err != nil {
		return nil, err
	}
	f := jen.NewFile(pkgName)
	f.HeaderComment("Code generated by prompty-gen. DO NOT EDIT.")

	sorted := slices.Clone(specs)
	slices.SortFunc(sorted, func(a, b *PromptSpec) int {
		if a.ID < b.ID {
			return -1
		}
		if a.ID > b.ID {
			return 1
		}
		return 0
	})

	f.ImportName("github.com/skosovsky/prompty", "prompty")
	f.ImportName("github.com/go-playground/validator/v10", "validator")
	f.ImportName("bytes", "bytes")
	f.ImportName("context", "context")
	f.ImportName("encoding/json", "json")
	f.ImportName("fmt", "fmt")
	f.ImportName("io", "io")

	f.Type().Id("PromptID").String()
	f.Line()

	f.Var().Id("validate").Op("=").Qual("github.com/go-playground/validator/v10", "New").Call()
	f.Line()

	f.Type().Id("Recipe").Interface(
		jen.Id("PromptID").Params().Id("PromptID"),
		jen.Id("Descriptor").Params().Qual("github.com/skosovsky/prompty", "ManifestDescriptor"),
		jen.Id("CheckpointJSON").Params().Parens(jen.List(jen.Index().Byte(), jen.Error())),
		jen.Id("Execute").Params(
			jen.Id("ctx").Qual("context", "Context"),
			jen.Id("registry").Qual("github.com/skosovsky/prompty", "ManifestCheckpointRegistry"),
		).Parens(jen.List(jen.Op("*").Qual("github.com/skosovsky/prompty", "PromptExecution"), jen.Error())),
		jen.Id("ExecuteWithContract").Params(
			jen.Id("ctx").Qual("context", "Context"),
			jen.Id("registry").Qual("github.com/skosovsky/prompty", "ManifestCheckpointRegistry"),
			jen.Id("contract").Qual("github.com/skosovsky/prompty", "ToolContract"),
		).Parens(jen.List(jen.Op("*").Qual("github.com/skosovsky/prompty", "PromptExecution"), jen.Error())),
	)
	f.Line()

	interfaceMethods := []jen.Code{
		jen.Id("Index").Params().Id("PromptIndex"),
		jen.Id("Descriptor").Params(
			jen.Id("ctx").Qual("context", "Context"),
			jen.Id("id").Id("PromptID"),
		).Parens(jen.List(jen.Qual("github.com/skosovsky/prompty", "TemplateDescriptor"), jen.Error())),
	}

	var structFields []jen.Code
	for _, spec := range sorted {
		rootName := toPascal(spec.ID)
		if promptSpecRequiresComposeContext(spec) {
			interfaceMethods = append(
				interfaceMethods,
				jen.Id("New"+rootName+"RecipeWithComposeContext").Params(
					jen.Id("ctx").Qual("context", "Context"),
					jen.Id("input").Id(rootName+"Input"),
					jen.Id("compose").Id(rootName+"ComposeContext"),
				).Parens(jen.List(jen.Id(rootName+"Recipe"), jen.Error())),
			)
		} else {
			interfaceMethods = append(interfaceMethods, jen.Id("New"+rootName+"Recipe").Params(
				jen.Id("ctx").Qual("context", "Context"),
				jen.Id("input").Id(rootName+"Input"),
			).Parens(jen.List(jen.Id(rootName+"Recipe"), jen.Error())))
		}
		structFields = append(structFields, jen.Id(rootName).Op("*").Id(rootName+"Prompt"))
	}

	f.Type().Id("PromptCatalog").Interface(interfaceMethods...)
	f.Line()

	catalogFields := append(
		[]jen.Code{
			jen.Id("registry").Qual("github.com/skosovsky/prompty", "PromptCatalogRegistry"),
		},
		structFields...,
	)
	f.Type().Id("promptCatalog").Struct(catalogFields...)
	f.Line()

	initValues := []jen.Code{
		jen.Id("registry").Op(":").Id("r"),
	}
	for _, spec := range sorted {
		rootName := toPascal(spec.ID)
		initValues = append(initValues,
			jen.Id(rootName).Op(":").Op("&").Id(rootName+"Prompt").Values(
				jen.Id("registry").Op(":").Id("r"),
			),
		)
	}
	f.Func().Id("NewPromptCatalog").Params(
		jen.Id("r").Qual("github.com/skosovsky/prompty", "PromptCatalogRegistry"),
	).Id("PromptCatalog").Block(
		jen.Return(jen.Op("&").Id("promptCatalog").Values(initValues...)),
	)
	f.Line()

	addPromptEntryAndIndex(f, sorted)
	addCatalogIndexMethod(f)
	addCatalogDescriptorMethod(f)
	addCatalogTypedRecipeMethods(f, sorted)
	addAllPromptIDsFunc(f, sorted)

	return f, nil
}

func validateSharedPromptSpecs(specs []*PromptSpec) error {
	for _, spec := range specs {
		if spec == nil {
			return errors.New("shared types: prompt spec is required")
		}
		if spec.ID == "" {
			return errors.New("shared types: prompt id is required")
		}
		if spec.Descriptor.Digest == "" {
			return fmt.Errorf("shared types: prompt %q descriptor digest is required", spec.ID)
		}
		if spec.Descriptor.ID != "" && spec.Descriptor.ID != spec.ID {
			return fmt.Errorf(
				"shared types: prompt %q descriptor id mismatch: %q",
				spec.ID,
				spec.Descriptor.ID,
			)
		}
	}
	return nil
}

//nolint:funlen // keeps PromptEntry and PromptIndex generation close together.
func addPromptEntryAndIndex(f *jen.File, specs []*PromptSpec) {
	f.Type().Id("PromptEntry").Struct(
		jen.Id("ID").Id("PromptID"),
		jen.Id("metadata").Qual("github.com/skosovsky/prompty", "PromptMetadata"),
		jen.Id("requiredTools").Index().String(),
		jen.Id("descriptor").Qual("github.com/skosovsky/prompty", "ManifestDescriptor"),
		jen.Id("newRecipeFromJSON").Func().Params(
			jen.Qual("context", "Context"),
			jen.Index().Byte(),
		).Parens(jen.List(jen.Id("Recipe"), jen.Error())),
		jen.Id("decodeRecipeCheckpoint").Func().Params(
			jen.Index().Byte(),
		).Parens(jen.List(jen.Id("Recipe"), jen.Error())),
	)
	f.Line()

	f.Func().Params(jen.Id("e").Id("PromptEntry")).Id("Metadata").Params().
		Qual("github.com/skosovsky/prompty", "PromptMetadata").Block(
		jen.Id("metadata").Op(":=").Id("e").Dot("metadata"),
		jen.Id("metadata").Dot("Tags").Op("=").Add(
			jen.Append(jen.Index().String().Values(), jen.Id("e").Dot("metadata").Dot("Tags").Op("...")),
		),
		jen.Id("metadata").Dot("Capabilities").Op("=").Add(
			jen.Append(jen.Index().String().Values(), jen.Id("e").Dot("metadata").Dot("Capabilities").Op("...")),
		),
		jen.Id("metadata").
			Dot("Extras").
			Op("=").
			Qual("github.com/skosovsky/prompty", "CloneJSONDocument").
			Call(
				jen.Id("e").Dot("metadata").Dot("Extras"),
			),
		jen.Return(jen.Id("metadata")),
	)
	f.Line()

	f.Func().
		Params(jen.Id("e").Id("PromptEntry")).
		Id("RequiredTools").
		Params().
		Index().
		String().
		Block(
			jen.Return(jen.Append(jen.Index().String().Values(), jen.Id("e").Dot("requiredTools").Op("..."))),
		)
	f.Line()

	f.Func().Params(jen.Id("e").Id("PromptEntry")).Id("Descriptor").Params().
		Qual("github.com/skosovsky/prompty", "ManifestDescriptor").Block(
		jen.Return(jen.Id("e").Dot("descriptor")),
	)
	f.Line()

	f.Func().Params(jen.Id("e").Id("PromptEntry")).Id("NewRecipeFromJSON").Params(
		jen.Id("ctx").Qual("context", "Context"),
		jen.Id("payload").Index().Byte(),
	).Parens(jen.List(jen.Id("Recipe"), jen.Error())).Block(
		jen.If(jen.Id("e").Dot("newRecipeFromJSON").Op("==").Nil()).Block(
			jen.Return(jen.Nil(), jen.Qual("fmt", "Errorf").Call(
				jen.Lit("prompt index: no recipe decoder for %q"),
				jen.Id("e").Dot("ID"),
			)),
		),
		jen.Return(jen.Id("e").Dot("newRecipeFromJSON").Call(jen.Id("ctx"), jen.Id("payload"))),
	)
	f.Line()

	f.Func().Params(jen.Id("e").Id("PromptEntry")).Id("DecodeRecipeCheckpoint").Params(
		jen.Id("payload").Index().Byte(),
	).Parens(jen.List(jen.Id("Recipe"), jen.Error())).Block(
		jen.If(jen.Id("e").Dot("decodeRecipeCheckpoint").Op("==").Nil()).Block(
			jen.Return(jen.Nil(), jen.Qual("fmt", "Errorf").Call(
				jen.Lit("prompt index: no checkpoint decoder for %q"),
				jen.Id("e").Dot("ID"),
			)),
		),
		jen.Return(jen.Id("e").Dot("decodeRecipeCheckpoint").Call(jen.Id("payload"))),
	)
	f.Line()

	f.Type().Id("PromptIndex").Struct(
		jen.Id("registry").Qual("github.com/skosovsky/prompty", "PromptCatalogRegistry"),
	)
	f.Line()

	f.Func().Id("NewPromptIndex").Params(
		jen.Id("r").Qual("github.com/skosovsky/prompty", "PromptCatalogRegistry"),
	).Id("PromptIndex").Block(
		jen.Return(jen.Id("PromptIndex").Values(jen.Id("registry").Op(":").Id("r"))),
	)
	f.Line()

	cases := make([]jen.Code, 0, len(specs))
	for _, spec := range specs {
		cases = append(cases, jen.Case(jen.Id(idToConstName(spec.ID))).Block(
			jen.Id("metadata").Op("=").Add(promptMetadataLiteral(spec)),
			jen.Id("requiredTools").Op("=").Add(stringSliceLiteral(spec.RequiredTools)),
			jen.Id("descriptor").Op("=").Add(manifestDescriptorLiteral(spec)),
			jen.Id("newRecipeFromJSON").Op("=").Func().Params(
				jen.Id("ctx").Qual("context", "Context"),
				jen.Id("payload").Index().Byte(),
			).Parens(jen.List(jen.Id("Recipe"), jen.Error())).Block(
				recipeFromJSONBody(spec)...,
			),
			jen.Id("decodeRecipeCheckpoint").Op("=").Add(checkpointDecoderFunc(spec)),
		))
	}
	f.Func().Params(jen.Id("i").Id("PromptIndex")).Id("Lookup").Params(
		jen.Id("id").Id("PromptID"),
	).Parens(jen.List(jen.Id("PromptEntry"), jen.Bool())).Block(
		jen.Var().Id("newRecipeFromJSON").Func().Params(
			jen.Qual("context", "Context"),
			jen.Index().Byte(),
		).Parens(jen.List(jen.Id("Recipe"), jen.Error())),
		jen.Var().Id("decodeRecipeCheckpoint").Func().Params(
			jen.Index().Byte(),
		).Parens(jen.List(jen.Id("Recipe"), jen.Error())),
		jen.Var().Id("metadata").Qual("github.com/skosovsky/prompty", "PromptMetadata"),
		jen.Var().Id("requiredTools").Index().String(),
		jen.Var().Id("descriptor").Qual("github.com/skosovsky/prompty", "ManifestDescriptor"),
		jen.Switch(jen.Id("id")).Block(append(cases,
			jen.Default().Block(jen.Return(jen.Id("PromptEntry").Values(), jen.False())),
		)...),
		jen.Return(
			jen.Id("PromptEntry").Values(
				jen.Id("ID").Op(":").Id("id"),
				jen.Id("metadata").Op(":").Id("metadata"),
				jen.Id("requiredTools").Op(":").Id("requiredTools"),
				jen.Id("descriptor").Op(":").Id("descriptor"),
				jen.Id("newRecipeFromJSON").Op(":").Id("newRecipeFromJSON"),
				jen.Id("decodeRecipeCheckpoint").Op(":").Id("decodeRecipeCheckpoint"),
			),
			jen.True(),
		),
	)
	f.Line()

	f.Func().Params(jen.Id("i").Id("PromptIndex")).Id("NewRecipeFromJSON").Params(
		jen.Id("ctx").Qual("context", "Context"),
		jen.Id("id").Id("PromptID"),
		jen.Id("payload").Index().Byte(),
	).Parens(jen.List(jen.Id("Recipe"), jen.Bool(), jen.Error())).Block(
		jen.List(jen.Id("entry"), jen.Id("ok")).Op(":=").Id("i").Dot("Lookup").Call(jen.Id("id")),
		jen.If(jen.Op("!").Id("ok")).Block(
			jen.Return(jen.Nil(), jen.False(), jen.Nil()),
		),
		jen.Var().Id("err").Error(),
		jen.List(jen.Id("recipe"), jen.Id("err")).
			Op(":=").
			Id("entry").
			Dot("NewRecipeFromJSON").
			Call(
				jen.Id("ctx"),
				jen.Id("payload"),
			),
		jen.Return(jen.Id("recipe"), jen.True(), jen.Id("err")),
	)
	f.Line()

	checkpointCases := make([]jen.Code, 0, len(specs))
	for _, spec := range specs {
		checkpointCases = append(checkpointCases, jen.Case(jen.Id(idToConstName(spec.ID))).Block(
			jen.List(jen.Id("recipe"), jen.Id("err")).
				Op(":=").
				Add(checkpointDecoderFunc(spec)).
				Call(jen.Id("payload")),
			jen.Return(jen.Id("recipe"), jen.True(), jen.Id("err")),
		),
		)
	}
	f.Func().Params(jen.Id("i").Id("PromptIndex")).Id("DecodeRecipeCheckpoint").Params(
		jen.Id("id").Id("PromptID"),
		jen.Id("payload").Index().Byte(),
	).Parens(jen.List(jen.Id("Recipe"), jen.Bool(), jen.Error())).Block(
		jen.Switch(jen.Id("id")).Block(append(checkpointCases,
			jen.Default().Block(jen.Return(jen.Nil(), jen.False(), jen.Nil())),
		)...),
		jen.Return(jen.Nil(), jen.False(), jen.Nil()),
	)
	f.Line()
}

func addCatalogIndexMethod(f *jen.File) {
	f.Func().
		Params(jen.Id("c").Op("*").Id("promptCatalog")).
		Id("Index").
		Params().
		Id("PromptIndex").
		Block(
			jen.Return(jen.Id("NewPromptIndex").Call(jen.Id("c").Dot("registry"))),
		)
	f.Line()
}

func addCatalogTypedRecipeMethods(f *jen.File, specs []*PromptSpec) {
	for _, spec := range specs {
		rootName := toPascal(spec.ID)
		if promptSpecRequiresComposeContext(spec) {
			f.Func().
				Params(jen.Id("c").Op("*").Id("promptCatalog")).
				Id("New"+rootName+"RecipeWithComposeContext").
				Params(
					jen.Id("ctx").Qual("context", "Context"),
					jen.Id("input").Id(rootName+"Input"),
					jen.Id("compose").Id(rootName+"ComposeContext"),
				).
				Parens(jen.List(jen.Id(rootName+"Recipe"), jen.Error())).
				Block(
					jen.Return(jen.Id("c").Dot(rootName).Dot("NewRecipeWithComposeContext").Call(
						jen.Id("ctx"),
						jen.Id("input"),
						jen.Id("compose"),
					)),
				)
		} else {
			f.Func().Params(jen.Id("c").Op("*").Id("promptCatalog")).Id("New"+rootName+"Recipe").Params(
				jen.Id("ctx").Qual("context", "Context"),
				jen.Id("input").Id(rootName+"Input"),
			).Parens(jen.List(jen.Id(rootName+"Recipe"), jen.Error())).Block(
				jen.Return(jen.Id("c").Dot(rootName).Dot("NewRecipe").Call(jen.Id("ctx"), jen.Id("input"))),
			)
		}
		f.Line()
	}
}

func recipeFromJSONBody(spec *PromptSpec) []jen.Code {
	rootName := toPascal(spec.ID)
	promptValue := jen.Parens(
		jen.Op("&").
			Id(rootName + "Prompt").
			Values(jen.Id("registry").Op(":").Id("i").Dot("registry")),
	)
	registryGuard := jen.If(jen.Id("i").Dot("registry").Op("==").Nil()).Block(
		jen.Return(jen.Nil(), jen.Qual("fmt", "Errorf").Call(
			jen.Lit("prompt index: registry is required for %q"),
			jen.Lit(spec.ID),
		)),
	)
	if promptSpecRequiresComposeContext(spec) {
		body := []jen.Code{
			registryGuard,
			jen.Var().Id("decoded").Id(rootName + "RecipePayload"),
		}
		body = append(body, strictDecodeJSONBody("decoded")...)
		body = append(
			body,
			jen.If(jen.Id("err").Op("!=").Nil()).Block(
				jen.Return(jen.Nil(), jen.Qual("fmt", "Errorf").Call(
					jen.Lit("decode %s recipe payload: %w"),
					jen.Lit(spec.ID),
					jen.Id("err"),
				)),
			),
			jen.If(jen.Id("decoded").Dot("Compose").Op("==").Nil()).Block(
				jen.Return(jen.Nil(), jen.Qual("fmt", "Errorf").Call(
					jen.Lit("decode %s recipe payload: compose context is required"),
					jen.Lit(spec.ID),
				)),
			),
			jen.List(jen.Id("recipe"), jen.Err()).
				Op(":=").
				Add(promptValue).
				Dot("NewRecipeWithComposeContext").
				Call(
					jen.Id("ctx"),
					jen.Id("decoded").Dot("Input"),
					jen.Op("*").Id("decoded").Dot("Compose"),
				),
			jen.If(jen.Err().Op("!=").Nil()).Block(
				jen.Return(jen.Nil(), jen.Err()),
			),
			jen.Return(jen.Id("recipe"), jen.Nil()),
		)
		return body
	}
	body := []jen.Code{
		registryGuard,
		jen.Var().Id("input").Id(rootName + "Input"),
	}
	body = append(body, strictDecodeJSONBody("input")...)
	body = append(
		body,
		jen.If(jen.Id("err").Op("!=").Nil()).Block(
			jen.Return(jen.Nil(), jen.Qual("fmt", "Errorf").Call(
				jen.Lit("decode %s input: %w"),
				jen.Lit(spec.ID),
				jen.Id("err"),
			)),
		),
		jen.List(jen.Id("recipe"), jen.Err()).
			Op(":=").
			Add(promptValue).
			Dot("NewRecipe").
			Call(jen.Id("ctx"), jen.Id("input")),
		jen.If(jen.Err().Op("!=").Nil()).Block(
			jen.Return(jen.Nil(), jen.Err()),
		),
		jen.Return(jen.Id("recipe"), jen.Nil()),
	)
	return body
}

func strictDecodeJSONBody(target string) []jen.Code {
	return []jen.Code{
		jen.Var().Id("err").Error(),
		jen.Id("decoder").Op(":=").Qual("encoding/json", "NewDecoder").Call(
			jen.Qual("bytes", "NewReader").Call(jen.Id("payload")),
		),
		jen.Id("decoder").Dot("DisallowUnknownFields").Call(),
		jen.If(jen.Id("err").Op("=").Id("decoder").Dot("Decode").Call(jen.Op("&").Id(target)), jen.Id("err").Op("==").Nil()).
			Block(
				jen.If(jen.Id("err").Op("=").Id("decoder").Dot("Decode").Call(jen.Op("&").Struct().Values()), jen.Id("err").Op("!=").Qual("io", "EOF")).
					Block(
						jen.If(jen.Id("err").Op("==").Nil()).Block(
							jen.Id("err").
								Op("=").
								Qual("fmt", "Errorf").
								Call(jen.Lit("unexpected trailing JSON value")),
						),
					).
					Else().
					Block(
						jen.Id("err").Op("=").Nil(),
					),
			),
	}
}

func promptSpecRequiresComposeContext(spec *PromptSpec) bool {
	return spec != nil && len(spec.ComposeConditions) > 0
}

func checkpointDecoderFunc(spec *PromptSpec) jen.Code {
	rootName := toPascal(spec.ID)
	checkpointType := jen.Qual("github.com/skosovsky/prompty", "PromptRecipeNoLateCheckpoint").
		Types(jen.Id(rootName + "Input"))
	if promptSpecHasLateInput(spec) {
		checkpointType = jen.Qual("github.com/skosovsky/prompty", "PromptRecipeCheckpoint").Types(
			jen.Id(rootName+"Input"),
			jen.Id(rootName+"LateInput"),
		)
	}
	body := []jen.Code{
		jen.Var().Id("checkpoint").Add(checkpointType),
	}
	body = append(body, strictDecodeJSONBody("checkpoint")...)
	body = append(
		body,
		jen.If(jen.Id("err").Op("!=").Nil()).Block(
			jen.Return(jen.Nil(), jen.Qual("fmt", "Errorf").Call(
				jen.Lit("decode %s recipe checkpoint: %w"),
				jen.Lit(spec.ID),
				jen.Id("err"),
			)),
		),
		jen.List(jen.Id("recipe"), jen.Err()).
			Op(":=").
			Id("New"+rootName+"RecipeFromCheckpoint").
			Call(jen.Id("checkpoint")),
		jen.If(jen.Err().Op("!=").Nil()).Block(
			jen.Return(jen.Nil(), jen.Err()),
		),
		jen.Return(jen.Id("recipe"), jen.Nil()),
	)
	return jen.Func().
		Params(jen.Id("payload").Index().Byte()).
		Parens(jen.List(jen.Id("Recipe"), jen.Error())).
		Block(body...)
}

func promptMetadataLiteral(spec *PromptSpec) jen.Code {
	meta := prompty.PromptMetadata{}
	if spec != nil {
		meta = spec.Metadata
		if meta.ID == "" {
			meta.ID = spec.ID
		}
	}
	fields := []jen.Code{jen.Id("ID").Op(":").Lit(meta.ID)}
	if meta.Version != "" {
		fields = append(fields, jen.Id("Version").Op(":").Lit(meta.Version))
	}
	if meta.Description != "" {
		fields = append(fields, jen.Id("Description").Op(":").Lit(meta.Description))
	}
	if len(meta.Tags) > 0 {
		fields = append(fields, jen.Id("Tags").Op(":").Add(stringSliceLiteral(meta.Tags)))
	}
	if len(meta.Capabilities) > 0 {
		fields = append(
			fields,
			jen.Id("Capabilities").Op(":").Add(stringSliceLiteral(meta.Capabilities)),
		)
	}
	if meta.Environment != "" {
		fields = append(fields, jen.Id("Environment").Op(":").Lit(meta.Environment))
	}
	if len(meta.Extras) > 0 {
		fields = append(
			fields,
			jen.Id("Extras").
				Op(":").
				Qual("github.com/skosovsky/prompty", "JSONDocument").
				Call(jen.Lit(string(meta.Extras))),
		)
	}
	return jen.Qual("github.com/skosovsky/prompty", "PromptMetadata").Values(fields...)
}

func manifestDescriptorLiteral(spec *PromptSpec) jen.Code {
	desc := prompty.ManifestDescriptor{ID: "", Digest: ""}
	if spec != nil {
		desc = spec.Descriptor
		if desc.ID == "" {
			desc.ID = spec.ID
		}
	}
	return jen.Qual("github.com/skosovsky/prompty", "ManifestDescriptor").Values(
		jen.Id("ID").Op(":").Lit(desc.ID),
		jen.Id("Digest").Op(":").Lit(desc.Digest),
	)
}

func stringSliceLiteral(values []string) jen.Code {
	lits := make([]jen.Code, len(values))
	for i, v := range values {
		lits[i] = jen.Lit(v)
	}
	return jen.Index().String().Values(lits...)
}

func promptSpecHasLateInput(spec *PromptSpec) bool {
	if spec == nil || spec.InputSchema == nil || len(spec.InputSchema.Schema) == 0 {
		return false
	}
	schema, err := schemaAsMap(spec.InputSchema.Schema)
	if err != nil {
		return false
	}
	_, _, hasLate := splitEarlyLateInputSchema(schema)
	return hasLate
}

func addAllPromptIDsFunc(f *jen.File, specs []*PromptSpec) {
	litVals := make([]jen.Code, len(specs))
	for i, spec := range specs {
		litVals[i] = jen.Id(idToConstName(spec.ID))
	}
	f.Func().Id("AllPromptIDs").Params().Index().Id("PromptID").Block(
		jen.Return(jen.Index().Id("PromptID").Values(litVals...)),
	)
}

func addCatalogDescriptorMethod(f *jen.File) {
	f.Func().Params(jen.Id("c").Op("*").Id("promptCatalog")).Id("Descriptor").Params(
		jen.Id("ctx").Qual("context", "Context"),
		jen.Id("id").Id("PromptID"),
	).Parens(jen.List(jen.Qual("github.com/skosovsky/prompty", "TemplateDescriptor"), jen.Error())).Block(
		jen.If(jen.Id("c").Dot("registry").Op("==").Nil()).Block(
			jen.Return(
				jen.Qual("github.com/skosovsky/prompty", "TemplateDescriptor").Values(),
				jen.Qual("fmt", "Errorf").
					Call(jen.Lit("prompt catalog: registry is required for %q"), jen.Id("id")),
			),
		),
		jen.If(jen.List(jen.Id("_"), jen.Id("ok")).Op(":=").Id("c").Dot("Index").Call().Dot("Lookup").Call(jen.Id("id")), jen.Op("!").Id("ok")).
			Block(
				jen.Return(
					jen.Qual("github.com/skosovsky/prompty", "TemplateDescriptor").Values(),
					jen.Qual("fmt", "Errorf").
						Call(jen.Lit("prompt catalog: unknown prompt id %q"), jen.Id("id")),
				),
			),
		jen.Return(jen.Id("c").Dot("registry").Dot("DescribePrompt").Call(
			jen.Id("ctx"),
			jen.Id("string").Call(jen.Id("id")),
		)),
	)
	f.Line()
}
