package gen

import (
	"slices"

	"github.com/dave/jennifer/jen"
)

// GenerateSharedTypes produces the shared _shared_gen.go file for a package.
// Contains: type PromptID, Prompts per-prompt container, NewPrompts, package-level validate, AllPromptIDs.
func GenerateSharedTypes(pkgName string, specs []*PromptSpec) (*jen.File, error) {
	f := jen.NewFile(pkgName)
	f.HeaderComment("Code generated by prompty-gen. DO NOT EDIT.")

	sorted := slices.Clone(specs)
	slices.SortFunc(sorted, func(a, b *PromptSpec) int {
		if a.ID < b.ID {
			return -1
		}
		if a.ID > b.ID {
			return 1
		}
		return 0
	})

	f.ImportName("github.com/skosovsky/prompty", "prompty")
	f.ImportName("github.com/go-playground/validator/v10", "validator")

	f.Type().Id("PromptID").String()
	f.Line()

	f.Var().Id("validate").Op("=").Qual("github.com/go-playground/validator/v10", "New").Call()
	f.Line()

	var structFields []jen.Code
	for _, spec := range sorted {
		rootName := toPascal(spec.ID)
		structFields = append(structFields, jen.Id(rootName).Op("*").Id(rootName+"Prompt"))
	}
	f.Type().Id("Prompts").Struct(structFields...)
	f.Line()

	initDict := jen.Dict{}
	for _, spec := range sorted {
		rootName := toPascal(spec.ID)
		initDict[jen.Id(rootName)] = jen.Op("&").Id(rootName + "Prompt").Values(jen.Dict{
			jen.Id("registry"): jen.Id("r"),
		})
	}
	f.Func().Id("NewPrompts").Params(
		jen.Id("r").Qual("github.com/skosovsky/prompty", "Registry"),
	).Op("*").Id("Prompts").Block(
		jen.Return(jen.Op("&").Id("Prompts").Values(initDict)),
	)
	f.Line()

	litVals := make([]jen.Code, len(sorted))
	for i, spec := range sorted {
		litVals[i] = jen.Id(idToConstName(spec.ID))
	}
	f.Func().Id("AllPromptIDs").Params().Index().Id("PromptID").Block(
		jen.Return(jen.Index().Id("PromptID").Values(litVals...)),
	)

	return f, nil
}
